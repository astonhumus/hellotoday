// Generates supabase/seed.sql from public/data so the database starts with the current places, categories and songs.
import { readFileSync, writeFileSync } from "node:fs";
const j = p => JSON.parse(readFileSync(new URL(`../public/data/${p}`, import.meta.url), "utf8"));
const q = v => (v == null || v === "" ? "null" : `'${String(v).replace(/'/g, "''")}'`);
const n = v => (v == null ? "null" : Number(v));

const out = [];
j("states.json").forEach(s => out.push(`insert into public.states values (${q(s.id)}, ${q(s.name)}, ${n(s.center[0])}, ${n(s.center[1])}, ${n(s.zoom)}) on conflict (id) do nothing;`));
j("categories.json").forEach((c, i) => out.push(`insert into public.categories values (${q(c.id)}, ${q(c.label)}, ${q(c.color)}, ${q(c.icon)}, ${i}) on conflict (id) do nothing;`));
for (const s of j("states.json")) {
  j(`${s.id}/places.json`).forEach(p => out.push(
    `insert into public.places (id, state_id, category_id, name, district, lat, lng, description, phone, website, approx, visited, notes) values (${[
      q(p.id), q(s.id), q(p.category), q(p.name), q(p.district), n(p.lat), n(p.lng), q(p.desc), q(p.phone), q(p.website), !!p.approx, q(p.visited), q(p.notes)
    ].join(", ")}) on conflict (id) do nothing;`));
}
j("songs.json").forEach(s => out.push(`insert into public.songs (id, title, artist, language, lyrics, credit) values (${[s.id, s.title, s.artist, s.language, s.lyrics, s.credit].map(q).join(", ")}) on conflict (id) do nothing;`));
writeFileSync(new URL("../supabase/seed.sql", import.meta.url), "-- Generated by scripts/build-seed.mjs. Run after schema.sql.\n" + out.join("\n") + "\n");
console.log(out.length, "rows");
